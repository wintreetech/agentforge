#!/usr/bin/env node
/**
 * Generates supabase/seed.sql from the TypeScript catalogue so the database
 * and the app share one source of truth. Seeds catalogue data only — never
 * customers, orders, reviews or other fabricated activity.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { categories } from "../packages/catalog/src/categories.ts";
import { buildProducts } from "../packages/catalog/src/build.ts";
import { blogPosts } from "../apps/web/src/content/blog-data.ts";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const q = (v) => (v == null ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;
const products = buildProducts();
const out = ["-- Generated by scripts/generate-seed-sql.mjs. Do not edit by hand.", "begin;"];

categories.forEach((c, i) => out.push(`insert into categories (slug,name,nav_label,tagline,description,accent,sort_order) values (${[c.slug, c.name, c.navLabel, c.tagline, c.description, c.accent, i].map(q).join(",")}) on conflict (slug) do update set name=excluded.name, tagline=excluded.tagline, description=excluded.description;`));

for (const p of products) {
  out.push(
    `insert into products (id,slug,category_slug,subcategory,title,short_description,description,price_amount,currency,status,functional,delivery,hosting,difficulty,license,version,cost_per_run_low,cost_per_run_high,cost_note,benefits,use_cases,audience,industries,inputs,outputs,requirements,installation,providers,demo_available,seo_title,seo_description,seo_keywords,published_at) values (` +
      [p.id, p.slug, p.category, p.subcategory, p.title, p.shortDescription, p.description, p.priceCents, p.currency, p.status, p.functional, p.delivery, p.hosting, p.difficulty, p.license, p.version, p.costPerRunEur?.[0] ?? null, p.costPerRunEur?.[1] ?? null, p.costNote].map(q).join(",") +
      `,${arr(p.benefits)},${arr(p.useCases)},${arr(p.audience)},${arr(p.industries)},${arr(p.inputs)},${arr(p.outputs)},${arr(p.requirements)},${arr(p.installation)},${arr(p.providers)},${q(p.demoAvailable)},${q(p.seo.title)},${q(p.seo.description)},${arr(p.seo.keywords)},${q(p.publishedAt)}) on conflict (id) do update set title=excluded.title, short_description=excluded.short_description, description=excluded.description, updated_at=now();`,
  );
  p.images.forEach((im, i) => out.push(`insert into product_images (product_id,src,alt,kind,sort_order) values (${[p.id, im.src, im.alt, im.kind, i].map(q).join(",")});`));
  p.capabilities.forEach((f, i) => out.push(`insert into product_features (product_id,feature,sort_order) values (${[p.id, f, i].map(q).join(",")});`));
  p.integrations.forEach((x) => out.push(`insert into product_integrations (product_id,integration) values (${q(p.id)},${q(x)}) on conflict do nothing;`));
  p.faqs.forEach((f, i) => out.push(`insert into product_faqs (product_id,question,answer,sort_order) values (${[p.id, f.q, f.a, i].map(q).join(",")});`));
  out.push(`insert into product_licenses (product_id,license,price_amount) values (${[p.id, p.license, p.priceCents].map(q).join(",")}) on conflict do nothing;`);
  for (const c of p.changelog) out.push(`insert into product_versions (product_id,version,released_at,notes) values (${q(p.id)},${q(c.version)},${q(c.date)},${arr(c.notes)}) on conflict do nothing;`);
}
for (const b of blogPosts) out.push(`insert into blog_posts (slug,title,excerpt,body,tag,published_at) values (${[b.slug, b.title, b.excerpt, b.body, b.tag, b.date].map(q).join(",")}) on conflict (slug) do nothing;`);
for (const pr of ["openai", "anthropic", "gemini"]) out.push(`insert into ai_providers (id) values ('${pr}') on conflict do nothing;`);
out.push("commit;");

await writeFile(path.join(root, "supabase/seed.sql"), out.join("\n") + "\n");
console.log(`Wrote supabase/seed.sql (${products.length} products, ${categories.length} categories, ${blogPosts.length} posts).`);
